function normalize(text: string): string {
    return (text || "")
        .toLowerCase()
        .replace(/ё/g, "е")
        .replace(/[^a-zа-я0-9\s.,/-]/gi, " ")
        .replace(/\s+/g, " ")
        .trim();
}

// Разбиваем на значимые токены (слова длиной от 3 символов).
function tokenize(text: string): string[] {
    return normalize(text)
        .split(/[\s.,;:!?()"'/\\-]+/)
        .filter((t) => t.length >= 3);
}

